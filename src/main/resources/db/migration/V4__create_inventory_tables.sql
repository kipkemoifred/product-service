-- 1. Products Table
CREATE TABLE IF NOT EXISTS products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    product_code VARCHAR(100) NOT NULL,
    description VARCHAR(1000),
    category VARCHAR(100) NOT NULL,
    unit_of_measure VARCHAR(50) NOT NULL,
    unit_price NUMERIC(12, 2) NOT NULL,
    tax_type VARCHAR(50) NOT NULL,
    has_discount BOOLEAN NOT NULL DEFAULT FALSE,
    discount_rate NUMERIC(5, 2) NOT NULL DEFAULT 0.00,
    image_url VARCHAR(500),
    active BOOLEAN NOT NULL DEFAULT TRUE,
    synced_to_supplier_catalogue BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_products_code UNIQUE (product_code)
);

CREATE INDEX IF NOT EXISTS idx_product_code ON products(product_code);
CREATE INDEX IF NOT EXISTS idx_product_category ON products(category);
CREATE INDEX IF NOT EXISTS idx_product_name ON products(name);

-- 2. Inventory Stocks Table (Warehouse Stock)
CREATE TABLE IF NOT EXISTS inventory_stocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    available_quantity NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    ordered_quantity NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    reorder_threshold NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    last_updated TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_inventory_stocks_product UNIQUE (product_id),
    CONSTRAINT fk_inventory_stocks_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

-- 3. Vehicle Stocks Table (Stock Loaded on Delivery Vehicles)
CREATE TABLE IF NOT EXISTS vehicle_stocks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    vehicle_id VARCHAR(100) NOT NULL,
    product_id BIGINT NOT NULL,
    available_quantity NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    ordered_quantity NUMERIC(12, 2) NOT NULL DEFAULT 0.00,
    last_updated TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_vehicle_product UNIQUE (vehicle_id, product_id),
    CONSTRAINT fk_vehicle_stocks_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_vehicle_id ON vehicle_stocks(vehicle_id);

-- 4. Stock Movements Table (Audit Trail)
CREATE TABLE IF NOT EXISTS stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL,
    movement_type VARCHAR(50) NOT NULL,
    quantity_changed NUMERIC(12, 2) NOT NULL,
    previous_quantity NUMERIC(12, 2) NOT NULL,
    new_quantity NUMERIC(12, 2) NOT NULL,
    reason VARCHAR(500) NOT NULL,
    reference_number VARCHAR(100),
    vehicle_id VARCHAR(100),
    performed_by VARCHAR(100) NOT NULL,
    synced_to_back_office BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_stock_movements_product FOREIGN KEY (product_id) REFERENCES products(id) ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_movement_product ON stock_movements(product_id);
CREATE INDEX IF NOT EXISTS idx_movement_created_at ON stock_movements(created_at);
CREATE INDEX IF NOT EXISTS idx_movement_vehicle ON stock_movements(vehicle_id);

-- 5. Back Office Sync Logs Table
CREATE TABLE IF NOT EXISTS back_office_sync_logs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sync_type VARCHAR(100) NOT NULL,
    entity_id VARCHAR(100) NOT NULL,
    payload VARCHAR(2000) NOT NULL,
    status VARCHAR(50) NOT NULL,
    message VARCHAR(1000),
    synced_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
